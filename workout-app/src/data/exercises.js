export const getExerciseFamily = (exercise) => EXERCISE_FAMILIES[exercise.id] || exercise.name

export const groupExercises = (exerciseList) => {
  const grouped = new Map()

  exerciseList.forEach((exercise) => {
    const family = getExerciseFamily(exercise)
    const key = `${exercise.category}-${family}`
    const existing = grouped.get(key)

    if (existing) {
      existing.exercises.push(exercise)
      existing.primaryMuscles = [...new Set([...existing.primaryMuscles, ...exercise.primaryMuscles])]
    } else {
      grouped.set(key, {
        key,
        family,
        category: exercise.category,
        primaryMuscles: [...exercise.primaryMuscles],
        exercises: [exercise],
      })
    }
  })

  return [...grouped.values()]
}

